  let lang = localStorage.getItem(KEY) === "en" ? "en" : "zh";

  function t(key, value) {
    const entry = TEXT[lang][key] ?? TEXT.zh[key] ?? key;
    return typeof entry === "function" ? entry(value) : entry;
  }

  function apply(root = document) {
    document.documentElement.lang = lang === "en" ? "en" : "zh-Hant";
    document.title = t("title");
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      for (const pair of el.dataset.i18nAttr.split(",")) {
        const [attr, key] = pair.split(":");
        el.setAttribute(attr.trim(), t(key.trim()));
      }
    });
    root.querySelectorAll("[data-lang]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
    });
  }

  function set(next) {
    lang = next === "en" ? "en" : "zh";
    try {
      localStorage.setItem(KEY, lang);
    } catch {
      /* The choice lasts for this page only. */
    }
    apply();
  }

  function date(value) {
    if (lang === "zh") return `${value.getMonth() + 1}月${value.getDate()}日`;
    return new Intl.DateTimeFormat("en-US", { month: "short", day: "numeric" }).format(value);
  }

  return { t, apply, set, date, get: () => lang };
